// The error catalogue (§2.7), GENERATED from the compiler source — never hand-typed.
//
// Every `new <X>Error('CODE', 'message …')` in packages/sfs/src is one catalogue row:
// its code, the stage (file) that raises it, and the symptom (the message's own text,
// which already names the construct and the fix). A generated catalogue cannot drift
// from the codes the compiler actually throws, which is the whole point — a prose list
// of error codes rots the first time a code is added.
//
//   node packages/sfs/tools/gen-catalogue.mjs            # write the catalogue
//   node packages/sfs/tools/gen-catalogue.mjs --check    # byte-compare, exit 1 on drift

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..', '..');
const SRC = path.join(ROOT, 'packages/sfs/src');
const OUT = 'packages/sfs/config/error-catalogue.json';

/** Match `new SomethingError('ABC-1234', '…message…'` across one logical call. */
const CALL = /new\s+\w*Error\(\s*'([A-Z]{2,4}-\d{3,4})'\s*,\s*(`[^`]*`|'[^']*'|"[^"]*")/g;

/**
 * @returns {{code:string, stage:string, symptom:string}[]}
 */
export function scan() {
  /** @type {Map<string, {code:string, stage:string, symptom:string}>} */
  const rows = new Map();
  /** @param {string} dir @returns {void} */
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const abs = path.join(dir, entry.name);
      if (entry.isDirectory()) { walk(abs); continue; }
      if (!entry.name.endsWith('.mjs')) continue;
      const text = fs.readFileSync(abs, 'utf8');
      const stage = path.relative(SRC, abs).split(path.sep).join('/');
      for (const m of text.matchAll(CALL)) {
        const code = m[1];
        if (rows.has(code)) continue; // first raise site wins; codes are unique by design
        // The message literal begins with "CODE …"; the symptom is the text after it.
        const raw = m[2].slice(1, -1).replace(/\s+/g, ' ').trim();
        const symptom = raw.startsWith(code) ? raw.slice(code.length).trim() : raw;
        rows.set(code, { code, stage, symptom: symptom.slice(0, 200) });
      }
    }
  };
  walk(SRC);
  return [...rows.values()].sort((a, b) => a.code.localeCompare(b.code));
}

/** @returns {string} */
function render() {
  const rows = scan();
  return `${JSON.stringify({
    _provenance: 'GENERATED by packages/sfs/tools/gen-catalogue.mjs from every new <X>Error(code, message) in packages/sfs/src. Do not hand-edit; run the generator. §2.7.',
    count: rows.length,
    rows,
  }, null, 2)}\n`;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const text = render();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(path.join(ROOT, OUT)) ? fs.readFileSync(path.join(ROOT, OUT), 'utf8') : '';
    if (cur !== text) { console.error(`CAT-0001 ${OUT} is stale — run gen-catalogue.mjs`); process.exit(1); }
    console.log(`gen-catalogue --check: ${OUT} is byte-identical`);
    process.exit(0);
  }
  fs.mkdirSync(path.join(ROOT, 'packages/sfs/config'), { recursive: true });
  fs.writeFileSync(path.join(ROOT, OUT), text);
  console.log(`gen-catalogue: wrote ${OUT} · ${scan().length} codes`);
  process.exit(0);
}
